import { test, expect } from '@playwright/test';
import { openHotelPage } from './hotel-nav.js';
import { randomUUID } from 'node:crypto';

test.skip(process.env.HOTEL_LIVE_E2E !== '1', 'Requires an isolated hotel test database.');

test('live folio posts charges, receives split payments, prints checkout and completes cleaning', async ({ page, request }, testInfo) => {
  test.setTimeout(180000);
  const login = await request.post('/api/auth/login', { data: { username: 'admin', pin: '123456' } });
  expect(login.ok()).toBeTruthy();
  const auth = await login.json();
  const headers = { Authorization: `Bearer ${auth.token}` };
  const command = async (data) => {
    const response = await request.post('/api/hotel', { headers: { ...headers, 'Idempotency-Key': randomUUID() }, data });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  };
  const contextResponse = await request.get('/api/admin/business-days', { headers });
  expect(contextResponse.ok()).toBeTruthy();
  const context = await contextResponse.json();
  if (!context.activeSession) {
    const response = await request.post('/api/admin/business-days', { headers, data: { opening_cash: 0, opening_note: 'Isolated hotel folio browser test' } });
    expect(response.ok(), await response.text()).toBeTruthy();
  }
  await command({ type: 'property', name: 'Test Hotel', taxPercent: 13 });
  const roomId = `F${Date.now().toString(36).slice(-7)}${testInfo.project.name[0]}`;
  await command({ type: 'room', roomId, roomType: 'Folio test', floor: 5, capacity: 2, rate: 100.01 });
  const snapshot = await (await request.get('/api/hotel', { headers })).json();
  const start = snapshot.state.businessDate;
  const end = new Date(Date.parse(start) + 3 * 86400000).toISOString().slice(0, 10);
  const guest = `Folio guest ${roomId}`;
  const reservation = await command({ type: 'book', roomId, guest, start, end, guests: 2 });
  await command({ type: 'checkin', id: reservation.id });
  await page.addInitScript(({ token, user }) => {
    localStorage.setItem('pos_token', token);
    localStorage.setItem('pos_user', JSON.stringify(user));
  }, auth);
  await page.route('**/api/admin/reservations/alerts', (route) => route.fulfill({ json: { alerts: [] } }));
  await page.route('**/api/admin/leads/counts', (route) => route.fulfill({ json: { counts: {} } }));
  await page.route('**/api/waiter-requests?**', (route) => route.fulfill({ json: { counts: {} } }));
  await page.goto(`/admin/hotel/folios?guest=${reservation.id}`);
  await expect(page.getByRole('heading', { name: `Guest folio / ${reservation.id}` })).toBeVisible({ timeout: 30000 });
  await expect(page.getByRole('button', { name: 'Check out guest', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Post room nights' }).click();
  await expect(page.getByRole('row').filter({ hasText: `night of ${start}` })).toContainText('113.01');
  await page.getByRole('button', { name: 'Add charge', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Description').fill('Laundry');
  await dialog.getByLabel('Charge type').selectOption('LAUNDRY');
  await dialog.getByLabel('Unit price before tax (NPR)').fill('150.05');
  await dialog.getByRole('button', { name: 'Add charge' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Record payment', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Amount (NPR)', { exact: true }).fill('100');
  await dialog.getByRole('button', { name: 'Record guest payment', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Record payment', exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('Amount (NPR)', { exact: true })).toHaveValue('182.57');
  await dialog.getByLabel('Method').selectOption('Online');
  await dialog.getByRole('button', { name: 'Record guest payment', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const closingResponse = await request.get('/api/admin/business-days?view=closing', { headers });
  expect(closingResponse.ok(), await closingResponse.text()).toBeTruthy();
  const closing = (await closingResponse.json()).summary;
  expect(closing.cash.breakdown.hotel_collections).toBeGreaterThanOrEqual(100);
  expect(closing.collections.online_hotel_collections).toBeGreaterThanOrEqual(182.57);
  await page.screenshot({ path: testInfo.outputPath('hotel-settled-folio.png'), fullPage: true });
  await page.getByRole('button', { name: 'Check out guest', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Confirm this guest is departing today.').check();
  await dialog.getByRole('button', { name: 'Finalize checkout' }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Print invoice' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Record payment', exact: true })).not.toBeVisible();
  const popupPromise = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'Print invoice' }).click();
  const printed = await popupPromise;
  await expect(printed.getByRole('heading', { name: 'Test Hotel' })).toBeVisible();
  await expect(printed.getByText('TAX INVOICE')).toBeVisible();
  await expect(printed.getByText('ORIGINAL')).toBeVisible();
  await printed.screenshot({ path: testInfo.outputPath('hotel-statement.png'), fullPage: true });
  await printed.close();
  await openHotelPage(page, 'Housekeeping');
  const task = page.getByRole('article').filter({ hasText: guest });
  for (const label of ['Start cleaning', 'Send for inspection', 'Inspect & mark ready']) await task.getByRole('button', { name: label }).click();
  await expect(task).toContainText('Ready');
  await page.screenshot({ path: testInfo.outputPath('hotel-live-housekeeping.png'), fullPage: true });
  const final = (await (await request.get('/api/hotel', { headers })).json()).state;
  expect(final.rooms.find((room) => room.id === roomId).cleaning).toBe('ready');
  expect(final.bookings.find((booking) => booking.id === reservation.id).status).toBe('checked_out');
});
